LABELS = {"effnetb2": "EfficientNet-B2", "effnetb3": "EfficientNet-B3", "effnetb4": "EfficientNet-B4"}
README_START = "<!-- results:start -->"
README_END = "<!-- results:end -->"


def _mid_sentence(label: str) -> str:
    """Lower-case a label's first letter for use inside a sentence, keeping a leading acronym such as JPEG."""
    first = label.split(" ", 1)[0]
    return label if len(first) > 1 and first.isupper() else label[:1].lower() + label[1:]


def _pct(x: float | None, digits: int = 1) -> str:
    return "n/a" if x is None else f"{100 * x:.{digits}f}%"


def _table(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, frame.columns)) + " |"
    rule = "| " + " | ".join("---" for _ in frame.columns) + " |"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in frame.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def experiments_markdown(store: ArtifactStore) -> str:
    parts = ["# Experiments\n", "_Generated by `foodvision.pipeline` from `artifacts/`; do not edit by hand._\n"]
    if store.exists(Files.ASSIGNMENT_SUMMARY):
        a = store.read_csv(Files.ASSIGNMENT_SUMMARY)
        view = pd.DataFrame(
            {
                "Model": a["model"].map(LABELS),
                "Epochs": a["epochs"],
                "Train acc.": a["train_acc"].map(_pct),
                "Test acc.": a["test_acc"].map(_pct),
                "95% Wilson CI": [f"{_pct(lo)} to {_pct(hi)}" for lo, hi in zip(a["test_ci_low"], a["test_ci_high"])],
                "Test loss": a["test_loss"].map("{:.3f}".format),
                "Time (s)": a["train_seconds"].map("{:.0f}".format),
                "Selected": a["selected"].map({True: "yes", False: ""}),
            }
        )
        parts += [
            "## A. Assignment protocol\n",
            "Nine runs logged train and test loss and accuracy to TensorBoard every epoch. As the assignment "
            "requires, the best run is chosen on the test set, so its accuracy is optimistically biased.\n",
            _table(view),
            "",
        ]
    if store.exists(Files.SELECTION):
        sel = store.read_json(Files.SELECTION)
        table = pd.DataFrame(sel["table"])
        view = pd.DataFrame(
            {
                "Model": table["model"].map(LABELS),
                "Epochs": table["epochs"],
                "Mean val. acc.": table["val_acc_mean"].map(_pct),
                "SD across seeds": table["val_acc_sd"].map(lambda v: "n/a" if pd.isna(v) else f"{100 * v:.1f} pts"),
                "Mean val. loss": table["val_loss_mean"].map("{:.3f}".format),
            }
        )
        split = sel["split"]
        parts += [
            "## B. Research protocol\n",
            f"Training images were split into {split['train']} for training and {split['validation']} for "
            f"validation (stratified). Every configuration was trained with seeds {sel['seeds']}. "
            f"Selection rule: {sel['rule']}.\n",
            _table(view),
            f"\n**Selected:** {sel['label']} at {sel['epochs']} epochs.\n",
        ]
    if store.exists(Files.TEST_REPORT):
        t = store.read_json(Files.TEST_REPORT)
        lo, hi = t["accuracy_wilson"]
        boot = t["macro_f1_bootstrap"]
        parts += [
            "### Final test evaluation (confirmatory, used once)\n",
            f"- Accuracy: {_pct(t['accuracy'])} ({t['n_correct']}/{t['n_test']}), 95% Wilson CI {_pct(lo)} to {_pct(hi)}",
            f"- Macro-F1: {_pct(t['macro_f1'])}, 95% bootstrap CI {_pct(boot['low'])} to {_pct(boot['high'])}",
            f"- Weighted-F1: {_pct(t['weighted_f1'])}; cross-entropy {t['loss']:.3f}",
            "- Repeatability across seeds (same configuration): "
            + ", ".join(f"seed {r['seed']}: {_pct(r['test_acc'])}" for r in t["repeatability"]),
            "",
            "### Exploratory comparisons (after selection)\n",
            "Exact McNemar tests on the same test images with Holm correction; the accuracy difference has a "
            "paired-bootstrap 95% CI. Not significant does not mean equivalent.\n",
        ]
        rows = [
            {
                "Comparison": f"{LABELS[c['model_a']]} vs {LABELS[c['model_b']]}",
                "Accuracy": f"{_pct(c['acc_a'])} vs {_pct(c['acc_b'])}",
                "Difference (95% CI)": f"{_pct(c['difference']['estimate'])} "
                f"({_pct(c['difference']['low'])} to {_pct(c['difference']['high'])})",
                "Discordant": c["discordant"],
                "p": f"{c['p_value']:.3f}",
                "p (Holm)": f"{c['p_holm']:.3f}",
            }
            for c in t["comparisons"]
        ]
        if rows:
            parts.append(_table(pd.DataFrame(rows)))
    if store.exists(Files.CALIBRATION):
        c = store.read_json(Files.CALIBRATION)
        parts += [
            "\n### Calibration\n",
            f"Temperature fitted on validation data: T = {c['temperature']:.2f}. Test ECE "
            f"{c['uncalibrated']['ece']:.3f} before and {c['temperature_scaled']['ece']:.3f} after scaling "
            f"({c['n_bins']} bins; with about 150 test images, ECE is itself noisy).",
        ]
    if store.exists(Files.BN_ABLATION):
        bn = store.read_csv(Files.BN_ABLATION)
        pivot = bn.pivot_table(index=["model", "epochs"], columns="bn_statistics", values="val_acc").reset_index()
        pivot["model"] = pivot["model"].map(LABELS)
        for col in pivot.columns[2:]:
            pivot[col] = pivot[col].map(_pct)
        parts += ["\n### BatchNorm statistics ablation (validation only)\n", _table(pivot)]
    if store.exists(Files.OOD):
        parts += ["\n### Not-food check\n", _ood_markdown(store.read_json(Files.OOD))]
    parts += _analysis_markdown(store)
    return "\n".join(parts) + "\n"


def _analysis_markdown(store: ArtifactStore) -> list[str]:
    parts: list[str] = []
    if store.exists(Files.ANALYSIS):
        check = store.read_json(Files.ANALYSIS)["checkpoint_check"]
        verdict = "reproduced" if check["match"] else "did NOT reproduce"
        parts += [
            "\n## C. Analysis of the selected model\n",
            f"Checkpoint check: the saved model, reloaded exactly as the app loads it, {verdict} the test accuracy "
            f"({_pct(check['reloaded_clean_accuracy'])} against {_pct(check['reported_test_accuracy'])} reported).",
        ]
    if store.exists(Files.ROBUSTNESS):
        r = store.read_csv(Files.ROBUSTNESS)
        rows = r[r["corruption"] != "none"]
        pivot = rows.pivot_table(index="label", columns="severity", values="accuracy").reset_index()
        pivot.columns = ["Corruption", *[{1: "Mild", 2: "Medium", 3: "Strong"}[c] for c in pivot.columns[1:]]]
        for column in pivot.columns[1:]:
            pivot[column] = pivot[column].map(_pct)
        clean = float(r.loc[r["corruption"] == "none", "accuracy"].iloc[0])
        parts += [
            "\n### Robustness to everyday photo problems (exploratory)\n",
            f"Test accuracy on corrupted copies of the test photos (clean: {_pct(clean)}). No decision was made from "
            "these results.\n",
            _table(pivot),
        ]
        if "accepted_as_food" in r.columns:
            strong = rows[rows["severity"] == 3]
            worst = strong.sort_values("accepted_as_food").iloc[0]
            parts.append(f"\nAt strong corruption the not-food check accepted as little as "
                         f"{_pct(worst['accepted_as_food'])} of real food photos ({_mid_sentence(str(worst['label']))}).")
    if store.exists(Files.DATA_EFFICIENCY):
        summary = efficiency_summary(store.read_csv(Files.DATA_EFFICIENCY))
        view = pd.DataFrame(
            {
                "Training photos": summary["n_train"].round().astype(int),
                "Share of training split": summary["fraction"].map(lambda f: _pct(f, 0)),
                "Mean val. acc.": summary["val_acc_mean"].map(_pct),
                "SD across seeds": summary["val_acc_sd"].map(lambda v: "n/a" if pd.isna(v) else f"{100 * v:.1f} pts"),
                "Runs": summary["runs"],
            }
        )
        parts += [
            "\n### Data efficiency (validation)\n",
            "The selected configuration retrained on nested, class-balanced subsets with the same epochs and learning "
            "rate; the full-data row reuses the research runs.\n",
            _table(view),
        ]
    if store.exists(Files.FEATURE_MAP):
        fmap = store.read_csv(Files.FEATURE_MAP)
        parts.append(f"\nFeature map: {int((fmap['group'] == 'food').sum())} food and "
                     f"{int((fmap['group'] == 'non-food').sum())} non-food test photos projected with t-SNE (see the app).")
    return parts


def _ood_markdown(o: dict[str, Any]) -> str:
    if o.get("status") == "disabled":
        return "Not run (`ood.enabled: false`)."
    if o.get("status") != "ok":
        return f"Skipped: {o.get('reason', 'unknown reason')}."
    test, auroc = o["test"], o["test"]["auroc"]
    scores = pd.DataFrame(
        {
            "Score": [r["label"] for r in o["scores"]],
            "Validation AUROC": [f"{r['val_auroc']:.3f}" for r in o["scores"]],
            f"Validation FPR at {_pct(o['target_tpr'], 0)} TPR": [_pct(r["val_fpr_at_tpr"]) for r in o["scores"]],
            "Test AUROC": [f"{r['test_auroc']:.3f}" for r in o["scores"]],
        }
    )
    return "\n".join(
        [
            f"Selected on validation data: **{o['score_label']}**, threshold {o['threshold']:.3f} "
            f"(keeps {_pct(o['target_tpr'], 0)} of validation food photos). Rule: {o['selection_rule']}.\n",
            _table(scores),
            "",
            f"On the test photos (used once): {_pct(test['rejected_non_food'])} of {test['n_non_food']} non-food photos "
            f"rejected, {_pct(test['accepted_food'])} of {test['n_food']} food photos accepted; AUROC "
            f"{auroc['estimate']:.3f} (95% bootstrap CI {auroc['low']:.3f} to {auroc['high']:.3f}).\n",
            _sources_table(o),
            "",
            o["protocol_note"],
        ]
    )


def _sources_table(o: dict[str, Any]) -> str:
    return _table(
        pd.DataFrame(
            {
                "Collection": [r["label"] for r in o["per_source"]],
                "Test photos": [r["n"] for r in o["per_source"]],
                "Rejected": [_pct(r["rejected"]) for r in o["per_source"]],
            }
        )
    )


def _read(store: ArtifactStore, name: str) -> Any:
    return store.read_json(name) if store.exists(name) else None


def model_card_markdown(store: ArtifactStore) -> str:
    """A model card in the structure of Mitchell et al. (2019), filled entirely from the artifacts."""
    if not store.exists(Files.MODEL_META):
        return "# Model card\n\nRun the pipeline to generate this card.\n"
    m: dict[str, Any] = store.read_json(Files.MODEL_META)
    t = _read(store, Files.TEST_REPORT)
    c = _read(store, Files.CALIBRATION)
    o = _read(store, Files.OOD)
    sel = _read(store, Files.SELECTION)
    bench = _read(store, Files.BENCHMARK) or []
    metrics = m["metrics"]
    lo, hi = metrics["test_accuracy_wilson"]
    ood_ok = bool(o) and o.get("status") == "ok"
    n_test = t["n_test"] if t else None

    task = f"- **Task:** classify a food photo as one of {len(m['classes'])} classes ({', '.join(m['classes'])})"
    details = [
        task + (", after a check that flags photos unlike the training data." if ood_ok else "."),
        f"- **Architecture:** {m['label']} with torchvision ImageNet weights `{m['weights']}`. The feature extractor "
        "is frozen; a new `Dropout -> Linear` head is trained.",
        f"- **Training:** {m['epochs']} epochs, seed {m['seed']}, {m['trained_on']}.",
    ]
    if sel:
        details.append(
            f"- **Selection:** best of {len(sel['table'])} backbone and epoch-budget configurations by mean validation "
            f"accuracy over seeds {', '.join(map(str, sel['seeds']))}; the test set played no part."
        )
    details += [
        f"- **Preprocessing:** resize {m['transforms']['resize']} px ({m['transforms']['interpolation']}), centre crop "
        f"{m['transforms']['crop']} px, ImageNet normalisation.",
        f"- **Calibration:** temperature scaling, T = {m['temperature']:.2f}, fitted on validation data.",
    ]
    if ood_ok:
        details.append(
            f"- **Not-food check:** {_mid_sentence(o['score_label'])}, threshold {o['threshold']:.3f}, set to keep "
            f"{_pct(o['target_tpr'], 0)} of validation food photos."
        )
    details += [
        f"- **Checkpoint:** {m['file']['bytes'] / 1024:.0f} KB, storing only what training changed (head and BatchNorm "
        f"statistics) over the pinned pretrained weights. SHA-256 `{m['file']['sha256'][:16]}...`.",
        f"- **Version:** FoodVision Lab {m['environment'].get('foodvision', 'n/a')}, created {m['created_at']}. "
        "Code under the MIT licence.",
    ]

    out_of_scope = [
        "- Any decision about allergies, diet, nutrition or food safety, or anything else where a wrong label matters.",
        "- Foods other than these three: a burger or a salad will usually receive one of the three labels"
        + (" (the not-food check was tested on flowers and pets, not on other foods)." if ood_ok else "."),
        "- Photos of people, or any use that identifies or profiles people.",
    ]

    metric_text = (
        "Accuracy with a Wilson score interval; macro-F1 with a bootstrap interval; per-class precision, recall and F1; "
        "calibration (expected calibration error, negative log-likelihood, Brier score)"
    )
    if ood_ok:
        metric_text += "; for the not-food check, AUROC and the shares of food and non-food photos accepted"
    metric_text += "."

    evaluation = [
        f"- {n_test or 'The'} Food-101 test photos, held out from training and from every choice above."
    ]
    if ood_ok:
        collections = " and ".join(f"{v['label']} ({v['content']}; {v['citation']})" for v in o["sources"].values())
        evaluation.append(
            f"- {o['test']['n_non_food']} non-food test photos sampled from {collections}, separate from the "
            "validation sample used to set the threshold. Only scores are stored, never the images."
        )

    if sel:
        split = sel["split"]
        training = (
            f"{split['train']} photos for training and {split['validation']} for validation, split by class from the "
            "training part of the 20% pizza, steak and sushi subset of Food-101 (Bossard et al., 2014)."
        )
    else:
        training = "The training part of the 20% pizza, steak and sushi subset of Food-101 (Bossard et al., 2014)."
    training += " See `docs/DATASET_CARD.md`."

    analyses = [
        "| Metric | Value | 95% interval |",
        "| --- | --- | --- |",
        f"| Accuracy | {_pct(metrics['test_accuracy'])}"
        + (f" ({t['n_correct']}/{t['n_test']})" if t else "")
        + f" | {_pct(lo)} to {_pct(hi)} (Wilson) |",
    ]
    if t:
        boot = t["macro_f1_bootstrap"]
        per_class = pd.DataFrame(
            {
                "Class": [r["class"] for r in t["per_class"]],
                "Precision": [_pct(r["precision"]) for r in t["per_class"]],
                "Recall": [_pct(r["recall"]) for r in t["per_class"]],
                "F1": [_pct(r["f1"]) for r in t["per_class"]],
                "Photos": [r["support"] for r in t["per_class"]],
            }
        )
        repeat = ", ".join(f"{_pct(r['test_acc'])} (seed {r['seed']})" for r in t["repeatability"])
        analyses += [
            f"| Macro-F1 | {_pct(t['macro_f1'])} | {_pct(boot['low'])} to {_pct(boot['high'])} (bootstrap) |",
            f"| Cross-entropy | {t['loss']:.3f} | |",
            "",
            "Per class (test set):",
            "",
            _table(per_class),
            "",
            f"The same configuration trained with each seed scored {repeat}.",
        ]
    if c:
        u, s = c["uncalibrated"], c["temperature_scaled"]
        analyses += [
            "",
            f"Calibration, before and after temperature scaling: expected calibration error {u['ece']:.3f} and "
            f"{s['ece']:.3f}; negative log-likelihood {u['nll']:.3f} and {s['nll']:.3f}; Brier score {u['brier']:.3f} "
            f"and {s['brier']:.3f}.",
        ]
    if ood_ok:
        test, auroc = o["test"], o["test"]["auroc"]
        analyses += [
            "",
            f"Not-food check (test photos, used once): {_pct(test['rejected_non_food'])} of {test['n_non_food']} "
            f"non-food photos rejected and {_pct(test['accepted_food'])} of {test['n_food']} food photos accepted; "
            f"AUROC {auroc['estimate']:.3f} (95% bootstrap CI {auroc['low']:.3f} to {auroc['high']:.3f}).",
            "",
            _sources_table(o),
        ]
    if store.exists(Files.ROBUSTNESS):
        r = store.read_csv(Files.ROBUSTNESS)
        strong = r[r["severity"] == 3].sort_values("accuracy")
        analyses += [
            "",
            "Robustness (exploratory, corrupted copies of the test photos): at the strongest level tested, accuracy was "
            + "; ".join(f"{_mid_sentence(str(row.label))} {_pct(row.accuracy)}" for row in strong.itertuples()) + ".",
        ]
    cpu = [b for b in bench if b["model"] == m["arch"] and b["device"] == "cpu"]
    if cpu:
        analyses += ["", f"Speed: median {cpu[0]['median_ms']:.0f} ms per photo on CPU ({cpu[0]['threads']} threads)."]

    ethics = [
        "- No personal data was used for training. The app classifies uploaded photos in memory and does not store them.",
        "- Food-101 photos come from the Foodspotting website, so they reflect its users' cuisines and photo styles; the "
        "model may work worse for these dishes as prepared or photographed elsewhere.",
        "- Confident-looking numbers invite over-trust. The app shows calibrated probabilities, lets users require a "
        "minimum confidence"
        + (", flags photos that look unlike the training data" if ood_ok else "")
        + " and states these limits next to every prediction.",
    ]

    width = 100 * (hi - lo) / 2
    caveats = [
        f"- With {n_test or 'so few'} test photos the accuracy interval is about ±{width:.0f} percentage points, so "
        "differences of a point or two between models are not meaningful.",
        "- Grad-CAM heat maps summarise correlations in the last feature map; they are not causal explanations.",
        "- Calibration was fitted on a small validation split; treat probabilities as approximate.",
        "- Retrain and re-evaluate before using the model on other data or for another task.",
    ]
    if not ood_ok:
        caveats.insert(0, "- No not-food check: every image, food or not, receives one of the three labels.")
    if store.exists(Files.ROBUSTNESS):
        caveats.insert(0, "- Expect lower accuracy on blurred, dark, noisy, compressed or low-resolution photos; the "
                       "robustness results above show by how much.")

    environment = ", ".join(f"{k} {v}" for k, v in m["environment"].items() if v)
    sections = [
        f"# Model card: FoodVision {m['label']}",
        "_Generated from the pipeline's artifacts, so no number here was typed by hand. "
        "Structure after Mitchell et al. (2019)._",
        "## Model details\n" + "\n".join(details),
        "## Intended use\n"
        "- **Primary use:** showing transfer learning, honest evaluation, calibration and explainability in a "
        "portfolio app.\n"
        "- **Primary users:** students, practitioners and recruiters exploring the project.\n\n"
        "**Out of scope:**\n" + "\n".join(out_of_scope),
        "## Factors\nLighting, camera angle, plating, regional styles of each dish and plates with several foods can "
        "all change performance. The test set is too small to measure these factors separately.",
        "## Metrics\n" + metric_text,
        "## Evaluation data\n" + "\n".join(evaluation),
        "## Training data\n" + training,
        "## Quantitative analyses\n" + "\n".join(analyses),
        "## Ethical considerations\n" + "\n".join(ethics),
        "## Caveats and recommendations\n" + "\n".join(caveats),
        "## Environment\n" + environment + ".",
    ]
    return "\n\n".join(sections) + "\n"


def audit_markdown(store: ArtifactStore) -> str:
    if not store.exists(Files.AUDIT):
        return "# Data audit\n\nRun the pipeline to generate this audit.\n"
    a = store.read_json(Files.AUDIT)
    counts = pd.DataFrame(a["counts"]).fillna(0).astype(int)
    counts.index.name = "class"
    return f"""# Data audit

_Generated from `artifacts/data/audit.json`._

- Images: {a['n_images']}; corrupted: {a['n_corrupted']}; unsupported extensions: {len(a['unsupported_files'])}.
- Formats: {a['formats']}; colour modes: {a['modes']}.
- Width {a['width']['min']:.0f} to {a['width']['max']:.0f} px (median {a['width']['median']:.0f});
  height {a['height']['min']:.0f} to {a['height']['max']:.0f} px (median {a['height']['median']:.0f});
  aspect ratio {a['aspect_ratio']['min']:.2f} to {a['aspect_ratio']['max']:.2f}.
- Duplicate screening (difference hash, at most {a['near_duplicate_threshold_bits']} differing bits):
  {a['exact_duplicate_pairs']} exact pairs, {a['near_duplicate_pairs']} near pairs,
  {a['cross_split_pairs']} pairs spanning train and test, {a['conflicting_label_pairs']} pairs with different labels.

## Images per class and split

{_table(counts.reset_index())}
"""


def write_reports(store: ArtifactStore) -> None:
    store.write_text(Files.EXPERIMENTS_REPORT, experiments_markdown(store))
    store.write_text(Files.MODEL_CARD, model_card_markdown(store))
    store.write_text(Files.AUDIT_REPORT, audit_markdown(store))


def readme_results(store: ArtifactStore) -> str:
    """The README's results table, built from the artifacts so that no number in it is typed by hand."""
    report = store.read_json(Files.TEST_REPORT)
    sel = store.read_json(Files.SELECTION)
    meta = store.read_json(Files.MODEL_META)
    calibration = _read(store, Files.CALIBRATION)
    ood = _read(store, Files.OOD)
    bench = _read(store, Files.BENCHMARK) or []
    low, high = report["accuracy_wilson"]
    rows = [
        ("Selected model", f"{sel['label']}, {sel['epochs']} epochs, chosen on validation data over "
                           f"{len(sel['seeds'])} seeds"),
        ("Test accuracy", f"{_pct(report['accuracy'])} ({report['n_correct']} of {report['n_test']}), "
                          f"95% CI {_pct(low)} to {_pct(high)}"),
        ("Macro-F1", _pct(report["macro_f1"])),
    ]
    if calibration:
        rows.append(("Calibration error (ECE)", f"{calibration['uncalibrated']['ece']:.3f} before and "
                     f"{calibration['temperature_scaled']['ece']:.3f} after temperature scaling"))
    if ood and ood.get("status") == "ok":
        test = ood["test"]
        rows.append(("Not-food check", f"AUROC {test['auroc']['estimate']:.3f}; flags "
                     f"{_pct(test['rejected_non_food'], 0)} of non-food photos and keeps "
                     f"{_pct(test['accepted_food'], 0)} of food photos"))
    cpu = [b for b in bench if b["model"] == meta["arch"] and b["device"] == "cpu"]
    speed = f"; {cpu[0]['median_ms']:.0f} ms per photo on a CPU" if cpu else ""
    rows.append(("Model file", f"{meta['file']['bytes'] / 1024:.0f} KB delta checkpoint{speed}"))
    lines = ["| Result | Value |", "| --- | --- |", *(f"| {name} | {value} |" for name, value in rows)]
    lines += ["", "<sub>Generated from `artifacts/` by `python -m foodvision.reports`; "
                  "the test suite fails if this table and the results disagree.</sub>"]
    return "\n".join(lines)


def update_readme(path: Path, store: ArtifactStore) -> bool:
    """Rewrite the block between the README markers from the artifacts; return whether the file changed."""
    text = path.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        raise ValueError(f"{path} has no {README_START} ... {README_END} block")
    head, rest = text.split(README_START, 1)
    tail = rest.split(README_END, 1)[1]
    new = f"{head}{README_START}\n{readme_results(store)}\n{README_END}{tail}"
    if new != text:
        path.write_text(new, encoding="utf-8")
    return new != text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Refresh the README's results table from the artifacts.")
    parser.add_argument("--artifacts", type=Path, default=None, help="artifact folder (default: artifacts/)")
    parser.add_argument("--readme", type=Path, default=Path("README.md"))
    args = parser.parse_args(argv)
    changed = update_readme(args.readme, ArtifactStore(args.artifacts))
    print(f"{args.readme}: results table {'updated' if changed else 'already up to date'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
